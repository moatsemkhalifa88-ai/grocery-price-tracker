import { backtests } from "@/lib/queries";

export const dynamic = "force-dynamic";

export default async function About() {
  const bt = await backtests();
  const chains = [...new Set(bt.map((b) => b.chain_key))];
  const wins = chains.filter((c) => {
    const m = bt.find((b) => b.chain_key === c && b.model === "holt_damped");
    const n = bt.find((b) => b.chain_key === c && b.model === "naive");
    return m && n && m.mae < n.mae;
  }).length;

  return (
    <div className="prose">
      <h1 className="display page-title">איך זה עובד</h1>
      <p className="lede">איך הנתונים נאספים, נשמרים ומחושבים.</p>

      <h2>מקור הנתונים</h2>
      <p>
        חוק הגנת הצרכן (שקיפות מחירים), התשע״ה–2014, מחייב רשתות גדולות לפרסם בכל יום את המחירים והמבצעים של כל
        סניף כקובצי XML. שופרסל מפרסמת בפורטל משלה, ורמי לוי, אושר עד, יוחננוף וטיב טעם בפלטפורמת FTP משותפת. כל רשת
        מפרסמת בפורמט קצת שונה, ולכן יש פרסר אחד שמזהה מבנים (Item/Line, אותיות גדולות/קטנות, UTF-8/UTF-16/Windows-1255,
        ואפילו קבצים חתוכים) במקום פרסר נפרד לכל רשת.
      </p>

      <h2>היסטוריית מחירים (SCD Type 2)</h2>
      <p>
        במקום לשמור את כל הקובץ כל יום, נשמרת שורה חדשה רק כשמחיר משתנה. לכל שורה יש <code>valid_from</code> ו-
        <code>valid_to</code>, ומוצר שנעלם מקובץ מלא נסגר כ״ירד מהמדף״. כך נחסכים מעל 95% מהנפח, ואפשר לשחזר את המחיר
        בכל סניף בכל יום.
      </p>

      <h2>סל משותף ומדד מחירים</h2>
      <p>
        הסל כולל מוצרים עם ברקוד אחיד שנמכרים ברוב הרשתות. עלות הסל מחושבת רק על מוצרים שכל הרשתות מכרו באותו יום, כדי
        שההשוואה תהיה הוגנת. המדד הוא מדד ג׳בונס (ממוצע גיאומטרי של יחסי המחיר), כמו המדדים הבסיסיים שבהם משתמשת
        הלמ״ס במדד המחירים לצרכן.
      </p>

      <h2>מחירי מבצע</h2>
      <p>
        רשתות מדווחות מבצעי ״2 ב-10״ בצורה שונה: חלקן את מחיר החבילה וחלקן את מחיר היחידה. כשהמחיר המדווח גבוה ממחיר
        המדף וכמות המינימום גדולה מ-1, הוא מטופל כמחיר חבילה ומחולק בכמות. מבצעי מועדון מוצגים בנפרד ולא נכנסים למחיר
        האפקטיבי.
      </p>

      <h2>תחזית</h2>
      <p>
        המדד של כל רשת נחזה 14 יום קדימה בעזרת החלקה מעריכית של Holt עם מגמה מרוסנת. הפרמטרים נבחרים בחיפוש רשת, והמודל
        נבדק מול תחזית נאיבית (״מחר כמו היום״) ב-backtest מתגלגל.
        {chains.length > 0 && ` כרגע המודל מנצח את התחזית הנאיבית ב-${wins} מתוך ${chains.length} רשתות.`} התחזית
        משתפרת ככל שמצטברת היסטוריה.
      </p>

      <h2>איכות נתונים</h2>
      <p>
        כל קובץ נרשם ביומן עם סטטוס, מספר שורות ושגיאה אם הייתה. קובץ ישן שמגיע באיחור לא נטען, כדי לא לשבש את
        ההיסטוריה. בדיקות dbt מוודאות שאין תקופות מחיר חופפות, שהמחיר האפקטיבי לא גבוה ממחיר המדף, ושהמדד מתחיל ב-100.
      </p>
    </div>
  );
}
